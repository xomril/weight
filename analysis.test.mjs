import assert from 'node:assert/strict';
import {getDaily,windowStats,eventStats,weekendStats,chartData} from './analysis.mjs';
const obs=[{date:'2026-01-01',hour:7,weight:90},{date:'2026-01-01',hour:8,weight:92},{date:'2026-01-01',hour:20,weight:100},{date:'2026-01-04',hour:8,weight:94}];
assert.equal(getDaily(obs)[0].value,92);
assert.equal(getDaily(obs,true)[0].value,91);
const d=getDaily(obs);assert.equal(d.length,2);
assert.equal(windowStats(d,'2026-01-01','2026-01-04').value,93);
assert.equal(weekendStats(d).n,1);assert.equal(weekendStats(d).delta,2);
const c=chartData(d,'2026-01-01','2026-01-04');assert.equal(c.length,4);assert.equal(c[1].value,null);
assert.equal(chartData(d,'2026-01-01','2026-01-04',true)[3].value,null);
assert.equal(eventStats(d,{start:'2026-01-02',end:'2026-01-03'}).delta,null);
const fs=await import('node:fs');
const html=fs.readFileSync(new URL('./docs/index.html',import.meta.url),'utf8');
const helper=fs.readFileSync(new URL('./analysis.mjs',import.meta.url),'utf8');
assert.ok(html.includes(helper.replaceAll('export ','')),'inline calculation code matches tested module');
const dataset=JSON.parse(html.match(/const data=(.*);\n/)[1]);
const real=getDaily(dataset.observations);assert.equal(dataset.observations.length,230);assert.equal(real.length,202);
assert.equal(real[0].date,'2026-01-01');assert.equal(real.at(-1).date,'2026-11-22');
assert.equal(weekendStats(real).n,23);assert.ok(Math.abs(weekendStats(real).delta-(-0.0260869565217395))<1e-10);
assert.equal(windowStats(real,'2026-08-01','2026-08-31').value.toFixed(2),'94.30');
assert.equal(windowStats(real,'2026-10-01','2026-10-31').value.toFixed(2),'95.64');
assert.equal(eventStats(real,dataset.events.find(e=>e.title==='מינכן'),7).delta.toFixed(2),'0.69');
assert.equal(windowStats(real,'2026-09-23','2026-09-26').n,0);
console.log('Analysis and source-data regression checks passed');
